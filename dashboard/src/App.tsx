import { Faults } from "./features/faults/Faults";
import { Headline } from "./features/headline/Headline";
import { LeadTime } from "./features/leadtime/LeadTime";
import { ResultsTable } from "./features/table/ResultsTable";
import { fmtInt } from "./shared/format";
import { Empty, Failure, Loading } from "./shared/States";
import { useResults } from "./shared/useResults";

export default function App() {
  const [load, retry] = useResults();
  return (
    <div className="page">
      <header className="masthead">
        <p className="eyebrow mono">shopfloor-order-orchestrator · TypeScript · NATS JetStream · VDA 5050 · SAP EWM / MES</p>
        <h1>From ERP order to robot and back, for a year</h1>
        {load.state === "ready" && load.data.designs.length > 0 && (
          <p className="masthead-sub">
            {load.data.split === "heldout" ? "Held-out" : "Dev"} seeds {load.data.designs[0]!.seeds.join(", ")} · {load.data.days} days each · about{" "}
            {fmtInt(load.data.designs[0]!.orders.mean)} orders a year across four robot cells, six AMRs and a humanoid
          </p>
        )}
      </header>
      <main>
        {load.state === "loading" && <Loading />}
        {load.state === "error" && <Failure message={load.message} onRetry={retry} />}
        {load.state === "ready" && load.data.designs.length === 0 && <Empty />}
        {load.state === "ready" && load.data.designs.length > 0 && (
          <>
            <Headline data={load.data} />
            <Faults data={load.data} />
            <LeadTime data={load.data} />
            <ResultsTable data={load.data} />
          </>
        )}
      </main>
      <footer className="footer">
        Simulated shopfloor, network and ERP. Generated by <code>npm run lab -- heldout</code>; never edited by hand.
      </footer>
    </div>
  );
}
