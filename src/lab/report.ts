import { createHash } from "node:crypto";
import { DESIGNS } from "./designs.js";
import type { RunResult } from "./run.js";

export const BEGIN = "<!-- lab:begin (generated by npm run lab -- heldout; do not edit) -->";
export const END = "<!-- lab:end -->";

export interface Stat {
  mean: number;
  sd: number;
}

export function stat(xs: number[]): Stat {
  const n = xs.length;
  const mean = xs.reduce((a, b) => a + b, 0) / Math.max(1, n);
  const sd = n > 1 ? Math.sqrt(xs.reduce((a, b) => a + (b - mean) ** 2, 0) / (n - 1)) : 0;
  return { mean: round(mean), sd: round(sd) };
}

const round = (x: number) => Math.round(x * 100) / 100;

export const METRICS: Array<{ key: keyof RunResult; label: string; digits: number; better: "lower" | "higher" }> = [
  { key: "duplicateExecutions", label: "Duplicate physical executions", digits: 0, better: "lower" },
  { key: "manualResets", label: "Manual task resets", digits: 0, better: "lower" },
  { key: "erpDoubleBookings", label: "ERP double bookings", digits: 0, better: "lower" },
  { key: "leadP95Min", label: "Order lead time p95 (min)", digits: 0, better: "lower" },
  { key: "partitionLeadP95Min", label: "Lead time p95, orders hit by a cut (min)", digits: 0, better: "lower" },
  { key: "latePct", label: "Late orders (%)", digits: 1, better: "lower" },
  { key: "leadP50Min", label: "Lead time p50 (min)", digits: 1, better: "lower" },
  { key: "erpMissing", label: "Finished but never booked", digits: 0, better: "lower" },
  { key: "kbPerDay", label: "Cloud-edge traffic (KB/day)", digits: 0, better: "lower" },
];

export function summarise(split: string, runs: RunResult[]) {
  const designs = DESIGNS.map((d) => {
    const rs = runs.filter((r) => r.design === d.name);
    const m: Record<string, Stat> = {};
    for (const k of METRICS) m[k.key] = stat(rs.map((r) => r[k.key] as number));
    return { design: d.name, label: d.label, seeds: rs.map((r) => r.seed), orders: stat(rs.map((r) => r.orders)), metrics: m };
  });
  return { split, days: runs[0]?.days ?? 0, generatedBy: `npm run lab -- ${split}`, designs };
}

export type Summary = ReturnType<typeof summarise>;

const fmt = (s: Stat, digits: number) => `${s.mean.toLocaleString("en-GB", { maximumFractionDigits: digits, minimumFractionDigits: digits })} ± ${s.sd.toLocaleString("en-GB", { maximumFractionDigits: digits, minimumFractionDigits: digits })}`;

export function markdown(s: Summary): string {
  const n = s.designs[0]?.seeds.length ?? 0;
  const lines = [
    `${s.split === "heldout" ? "Held-out" : s.split[0]!.toUpperCase() + s.split.slice(1)} run: ${n} seeds × ${s.days} days, about ${Math.round(s.designs[0]!.orders.mean).toLocaleString("en-GB")} ERP/MES orders each. Mean ± sd across seeds, per simulated year.`,
    "",
    `| Metric | ${s.designs.map((d) => d.label).join(" | ")} |`,
    `|---|${s.designs.map(() => "---:").join("|")}|`,
  ];
  for (const m of METRICS) lines.push(`| ${m.label} | ${s.designs.map((d) => fmt(d.metrics[m.key]!, m.digits)).join(" | ")} |`);
  const base = s.designs.find((d) => d.design === "point-to-point")!;
  const orch = s.designs.find((d) => d.design === "orchestrator")!;
  const change = (k: string) => {
    const a = base.metrics[k]!.mean;
    const b = orch.metrics[k]!.mean;
    return a === 0 ? "n/a" : `${b - a > 0 ? "+" : ""}${Math.round((100 * (b - a)) / a)} %`;
  };
  lines.push("", `Orchestrator vs point-to-point: lead time p95 ${change("leadP95Min")}, late orders ${change("latePct")}, duplicate executions ${change("duplicateExecutions")}, manual resets ${change("manualResets")}, ERP double bookings ${change("erpDoubleBookings")}.`);
  return lines.join("\n") + "\n";
}

export const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
